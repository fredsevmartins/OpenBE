#' Generate reproducible scientific design and analysis figures
#'
#' Writes PNG at 300 dpi and vector PDF. Endpoint-only data do not yield
#' concentration-time profiles. Replicate figures compare Methods A and B and
#' show the historical scaling curve, explicitly as a numerical illustration.
#' @param result Analysis result from an OpenBE analysis function.
#' @param directory Output directory.
#' @param title Informative study title.
#' @param provenance Source description and observed/simulated classification.
#' @param script Relative path of the generating script.
#' @return Character vector of generated filenames, invisibly.
#' @export
plot_analysis <- function(result, directory, title, provenance, script) {
  dir.create(directory, recursive = TRUE, showWarnings = FALSE)
  d <- result$data; s <- result$summary
  cap <- paste(provenance, "Generated by", script)
  save <- function(p, name) {
    p <- p + ggplot2::theme_minimal(base_size = 11) +
      ggplot2::labs(caption = cap) + ggplot2::theme(plot.caption = ggplot2::element_text(size = 7))
    for (ext in c("png","pdf")) ggplot2::ggsave(file.path(directory,paste0(name,".",ext)),
      p, width = 9, height = 5.5, dpi = 300, bg = "white")
  }
  design <- unique(d[c("sequence","period","treatment")])
  save(ggplot2::ggplot(design, ggplot2::aes(x = period,y = sequence,fill = treatment)) +
    ggplot2::geom_tile(color = "white",linewidth = 2) +
    ggplot2::geom_text(ggplot2::aes(label = treatment),color = "white",fontface = "bold") +
    ggplot2::scale_fill_manual(values = c(R = "#156082", T = "#d05a36", A = "#d05a36",B = "#658d4c",C = "#8265a7")) +
    ggplot2::labs(title = paste(title,"- allocation"),subtitle = paste(nlevels(d$sequence),"sequences"),
                  x = "Period",y = "Sequence"), "design")
  s$label <- if ("method" %in% names(s)) paste("Method",s$method) else
    if ("comparison" %in% names(s)) s$comparison else "T / R"
  p <- ggplot2::ggplot(s, ggplot2::aes(x = gmr,y = label)) +
    ggplot2::geom_vline(xintercept = c(0.8,1.25),linetype = 2,color = "#a23b2a") +
    ggplot2::geom_vline(xintercept = 1,color = "grey65") +
    ggplot2::geom_segment(ggplot2::aes(x = lower,xend = upper,yend = label),linewidth = 0.8) +
    ggplot2::geom_point(size = 3,color = "#156082") +
    ggplot2::labs(title = paste(title,"- ratio and 90% CI"),x = "Geometric mean ratio (unitless)",y = NULL)
  if ("abel_lower" %in% names(s)) p <- p + ggplot2::geom_vline(
    xintercept = c(s$abel_lower[1],s$abel_upper[1]),linetype = 3,color = "#658d4c")
  save(p, "gmr")
  z <- data.frame(fitted = as.numeric(stats::fitted(result$model)),
                   residual = as.numeric(stats::residuals(result$model)))
  save(ggplot2::ggplot(z, ggplot2::aes(x = fitted,y = residual)) +
    ggplot2::geom_point(alpha = 0.6,color = "#156082") + ggplot2::geom_hline(yintercept = 0,linetype = 2) +
    ggplot2::labs(title = paste(title,"- residual diagnostics"),
      x = "Fitted log endpoint",y = "Residual (log units)"), "residuals")
  save(ggplot2::ggplot(z, ggplot2::aes(sample = residual)) + ggplot2::stat_qq() + ggplot2::stat_qq_line() +
    ggplot2::labs(title = paste(title,"- normal Q-Q"),x = "Theoretical quantile",y = "Residual quantile"),"qq")
  if ("cv_wR" %in% names(s)) {
    v <- data.frame(treatment = c("R","T"),cv = c(s$cv_wR[1],s$cv_wT[1]))
    v <- v[is.finite(v$cv), ]
    save(ggplot2::ggplot(v, ggplot2::aes(x = treatment,y = 100*cv,fill = treatment)) +
      ggplot2::geom_col(width = 0.5) + ggplot2::scale_fill_manual(values = c(R="#156082",T="#d05a36")) +
      ggplot2::labs(title = paste(title,"- within-subject variability"),x="Treatment",y="Within-subject CV (%)"),"variability")
    x <- seq(0,0.8,length.out = 161)
    curve <- data.frame(cv = x,lower = vapply(x,function(z) abel_limits(z)[1],numeric(1)),
                         upper = vapply(x,function(z) abel_limits(z)[2],numeric(1)))
    save(ggplot2::ggplot(curve,ggplot2::aes(x=100*cv)) +
      ggplot2::geom_line(ggplot2::aes(y=lower),color="#156082") +
      ggplot2::geom_line(ggplot2::aes(y=upper),color="#d05a36") +
      ggplot2::geom_vline(xintercept=100*s$cv_wR[1],linetype=2) +
      ggplot2::labs(title="Historical ABEL limits - computational illustration",
                    x="Reference within-subject CV (%)",y="Ratio acceptance limit"),"scaling")
    save(ggplot2::ggplot(s,ggplot2::aes(x=method,y=df)) + ggplot2::geom_col(fill="#156082",width=.5) +
      ggplot2::labs(title=paste(title,"- degrees of freedom"),x="Method",y="Treatment contrast DF"),"methods")
  }
  invisible(list.files(directory,full.names=TRUE))
}
