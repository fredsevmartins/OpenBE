library(OpenBE)
library(ggplot2)
dir.create("examples/planning/outputs",recursive=TRUE,showWarnings=FALSE)
grid <- expand.grid(cv=c(.15,.2,.3,.4),ratio=c(.9,.95,1),design=c("2x2","2x2x4"),stringsAsFactors=FALSE)
results <- do.call(rbind,lapply(seq_len(nrow(grid)),function(i) {
 z<-grid[i, ]; p<-plan_be(z$cv,z$ratio,design=z$design)
 data.frame(z,n=p[["Sample size"]],achieved_power=p[["Achieved power"]])
}))
write.csv(results,"examples/planning/outputs/sensitivity.csv",row.names=FALSE)
scaled <- plan_be(cv=.4,design="2x2x4",scaled=TRUE)
write.csv(scaled,"examples/planning/outputs/scaled-planning.csv",row.names=FALSE)
write.csv(PowerTOST::known.designs(),"examples/planning/outputs/known-designs.csv",row.names=FALSE)
writeLines(capture.output(sessionInfo()),"examples/planning/outputs/sessionInfo.txt")
p<-ggplot(results,aes(x=100*cv,y=n,color=factor(ratio),group=ratio))+geom_line()+geom_point()+
 facet_wrap(~design)+theme_minimal()+labs(title="Sample-size sensitivity: conventional TOST planning",
 x="Assumed within-subject CV (%)",y="Total subjects",color="Expected GMR",
 caption="PowerTOST::sampleN.TOST; target power 80%. Generated by scripts/run_planning.R.")
for(ext in c("png","pdf")) ggsave(paste0("examples/planning/outputs/sensitivity.",ext),p,width=9,height=5.5,dpi=300)
