library(OpenBE)
d <- read.csv(system.file("extdata","theoph.csv",package="OpenBE"))
conc <- data.frame(subject=d$Subject,time=d$Time,concentration=d$conc)
dose <- unique(data.frame(subject=d$Subject,time=0,dose=d$Dose))
intervals <- data.frame(start=0,end=Inf,cmax=TRUE,tmax=TRUE,auclast=TRUE,
                       aucinf.obs=TRUE,half.life=TRUE,lambda.z=TRUE,aucpext.obs=TRUE)
nca <- analyze_nca(conc,dose,intervals,"mg/L","h","mg/kg")
dir.create("examples/pharmacokinetics/outputs",recursive=TRUE,showWarnings=FALSE)
write_nca(nca,"examples/pharmacokinetics/outputs")
writeLines(capture.output(PKNCA::PKNCA.options()),"examples/pharmacokinetics/outputs/pknca-options.txt")
writeLines(capture.output(sessionInfo()),"examples/pharmacokinetics/outputs/sessionInfo.txt")
library(ggplot2)
d$subject <- factor(d$Subject)
for (scale in c("linear","semilog")) {
  plotdata <- if (scale=="semilog") d[d$conc>0, ] else d
  p <- ggplot(plotdata,aes(x=Time,y=conc,group=subject)) + geom_line(alpha=.4,color="#156082") +
    geom_point(alpha=.4,size=1) + theme_minimal() +
    labs(title="Observed theophylline concentration-time profiles",x="Time (h)",y="Concentration (mg/L)",
      caption="datasets::Theoph; observed oral data. Generated by scripts/run_nca.R. Doses vary by subject; zero concentrations omitted from logarithmic plots only.")
  if(scale=="semilog") p <- p + scale_y_log10()
  for (ext in c("png","pdf")) ggsave(paste0("examples/pharmacokinetics/outputs/profiles_",scale,".",ext),p,
                                   width=9,height=5.5,dpi=300)
}

# Align by nominal sample order only; actual times vary and are not interpolated.
d$sample_index <- ave(d$Time,d$Subject,FUN=seq_along)
means <- aggregate(cbind(Time,conc)~sample_index,d,mean)
write.csv(means,"examples/pharmacokinetics/outputs/mean-profile.csv",row.names=FALSE)
for(scale in c("linear","semilog")) {
 p<-ggplot(means,aes(x=Time,y=conc))+geom_line(color="#156082")+geom_point()+theme_minimal()+
 labs(title="Theophylline arithmetic mean profile by nominal sample order",x="Mean actual sampling time (h)",
 y="Mean concentration (mg/L)",caption="Observed datasets::Theoph; doses vary. No time interpolation. scripts/run_nca.R")
 if(scale=="semilog") p<-p+scale_y_log10()
 for(ext in c("png","pdf")) ggsave(paste0("examples/pharmacokinetics/outputs/mean_",scale,".",ext),p,width=9,height=5.5,dpi=300)
}
